"""Turn the before/final responsive audits into docs/MOBILE_RESPONSIVE_AUDIT.md (per route × defect, before vs after)."""
import json, collections
from pathlib import Path

D = Path(__file__).resolve().parents[1] / "docs"
B = json.loads((D / "responsive-screenshots/before/audit.json").read_text())
F = json.loads((D / "responsive-screenshots/final/audit.json").read_text())


def defects(rows):
    out = collections.defaultdict(lambda: collections.defaultdict(list))
    for x in rows:
        r, w = x["route"], f"{x['w']}×{x['h']}"
        if x.get("error"): out[r]["load timeout"].append(w); continue
        if x["doc_overflow"] > 1: out[r]["page overflow"].append(w)
        if x["escapees"]: out[r]["element past viewport"].append(w)
        if x["giant_badges"]: out[r]["label stretched into empty panel (P1)"].append(w)
        if x["tiny_svg_text"] and not r.startswith("rules/atlas"): out[r]["chart labels < 7 px (P1)"].append(w)
        if x["small_targets"]: out[r]["touch targets < 40 px (P2)"].append(w)
        if x["errors"]: out[r]["console error (P0)"].append(w)
    return out


db, df = defects(B), defects(F)
routes = sorted({x["route"] for x in B})
vps = sorted({(x["w"], x["h"]) for x in B})
L = ["# Mobile & responsive audit", "",
     f"Generated by `scripts/responsive_report.py` from `docs/responsive-screenshots/{{before,final}}/audit.json` (produced by `scripts/responsive_audit.py`, headless Microsoft Edge).",
     f"**{len(routes)} routes × {len(vps)} viewports = {len(B)} renders per phase.** Viewports: " + ", ".join(f"{w}×{h}" for w, h in vps) + ".", "",
     "Viewport sizes are browser emulations (with mobile/touch flags below 768/1024 px), not physical devices.", "",
     "## Totals", "", "| Check | Before (renders) | Final (renders) |", "|---|---|---|"]
for k in ["page overflow", "element past viewport", "label stretched into empty panel (P1)", "chart labels < 7 px (P1)", "touch targets < 40 px (P2)", "console error (P0)", "load timeout"]:
    L.append(f"| {k} | {sum(len(v.get(k, [])) for v in db.values())} | {sum(len(v.get(k, [])) for v in df.values())} |")
L += ["", "The dependency atlas is excluded from the label-size check: it is a zoomable graph (buttons, drag, touch) whose initial view shows the whole structure.", "",
      "## Per route", "", "| Route | Defects before (viewports) | Status after |", "|---|---|---|"]
for r in routes:
    b = "; ".join(f"{k}: {len(v)} vp ({', '.join(v[:3])}{'…' if len(v) > 3 else ''})" for k, v in db[r].items()) or "none found"
    f = "; ".join(f"{k}: {len(v)} vp ({', '.join(v[:3])})" for k, v in df[r].items()) or "verified clean at all viewports"
    L.append(f"| `#/{r}` | {b} | {f} |")
(D / "MOBILE_RESPONSIVE_AUDIT.md").write_text("\n".join(L) + "\n", encoding="utf-8")
print("written", len(routes), "routes")
